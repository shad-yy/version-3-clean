/**
 * Generates lib/geo/topology-map.ts — ISO 3166-1 numeric to alpha-2.
 *
 * The world topology keys its geometries by numeric ISO code ("826"), while every other
 * part of this codebase keys countries by alpha-2 ("GB"). The handoff is explicit that
 * the map must be keyed by ISO code rather than by country name, because names drift
 * between sources: the topology says "W. Sahara", "Dem. Rep. Congo" and
 * "United States of America" where Intl says "Western Sahara", "Congo - Kinshasa" and
 * "United States".
 *
 * Rather than hand-typing 177 pairs — where a single transposed digit would silently
 * colour the wrong country — this matches each topology name against Intl.DisplayNames
 * for every alpha-2 code, applies explicit overrides for the known naming differences,
 * and **reports anything still unmatched** so a gap is visible rather than silent.
 *
 * Run: node scripts/generate-country-map.mjs
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, "..")

const topo = JSON.parse(
  fs.readFileSync(path.join(ROOT, "public/geo/countries-110m.json"), "utf-8"),
)
const geometries = topo.objects.countries.geometries

// Every alpha-2 code, with the English name Intl gives it.
const ALPHA2 = []
for (let a = 65; a <= 90; a++) {
  for (let b = 65; b <= 90; b++) {
    const code = String.fromCharCode(a) + String.fromCharCode(b)
    let name
    try {
      name = new Intl.DisplayNames(["en"], { type: "region" }).of(code)
    } catch {
      continue
    }
    // Intl echoes the code back when it is not a real region.
    if (name && name !== code) ALPHA2.push({ code, name })
  }
}

const norm = (s) =>
  s
    .toLowerCase()
    .replace(/\band\b|&/g, "")
    .replace(/[^a-z]/g, "")

/**
 * Is this code a canonical ISO 3166-1 alpha-2 assignment, or a deprecated alias?
 *
 * Enumerating A-Z yields codes Intl resolves but which are not current assignments, and
 * they collide by name with the real ones. Two bit us in a row:
 *
 *   * `UK` resolves to "United Kingdom" and overwrote `GB` — the exact code Google
 *     ignores in hreflang, and the subject of OWNER-INSTRUCTIONS rule 3.
 *   * `DD` (East Germany) resolves to "Germany" and overwrote `DE`, so Germany rendered
 *     as "nothing recorded" for every title.
 *
 * A hand-kept blocklist would be whack-a-mole. CLDR already knows which codes are
 * aliases: canonicalising `und-DD` returns `und-DE`, while `und-DE` returns itself. So a
 * code is canonical exactly when canonicalising it gives back the same code.
 */
function isCanonicalRegion(code) {
  try {
    const canonical = Intl.getCanonicalLocales(`und-${code}`)[0] || ""
    return canonical.split("-").pop() === code
  } catch {
    return false
  }
}

const byName = new Map()
for (const c of ALPHA2) {
  if (!isCanonicalRegion(c.code)) continue
  const key = norm(c.name)
  if (!byName.has(key)) byName.set(key, c.code)
}

/** Names the topology spells differently from Intl. Each verified by hand. */
const OVERRIDES = {
  "United States of America": "US",
  "W. Sahara": "EH",
  "Dem. Rep. Congo": "CD",
  "Dominican Rep.": "DO",
  "Falkland Is.": "FK",
  "Fr. S. Antarctic Lands": "TF",
  "Bosnia and Herz.": "BA",
  "Central African Rep.": "CF",
  "Eq. Guinea": "GQ",
  "eSwatini": "SZ",
  "Solomon Is.": "SB",
  "S. Sudan": "SS",
  "N. Cyprus": "CY",
  "Somaliland": "SO",
  "Kosovo": "XK",
  "Czechia": "CZ",
  "Côte d'Ivoire": "CI",
  "Myanmar": "MM",
  "Timor-Leste": "TL",
  "Lao PDR": "LA",
  "Dem. Rep. Korea": "KP",
  "Korea": "KR",
  "Taiwan": "TW",
  "Macedonia": "MK",
  "Moldova": "MD",
  "Palestine": "PS",
  "Vatican": "VA",
  // Republic of the Congo. Distinct from Dem. Rep. Congo above, and Intl's name
  // ("Congo - Brazzaville") does not match the topology's bare "Congo".
  "Congo": "CG",
  // Intl now returns "Türkiye"; the topology still says "Turkey".
  "Turkey": "TR",
  "Antarctica": null, // Not a country; deliberately excluded.
}

const map = {}
const unmatched = []

for (const g of geometries) {
  const name = g.properties?.name
  const id = String(g.id)
  if (!name) continue

  if (name in OVERRIDES) {
    const code = OVERRIDES[name]
    if (code) map[id] = code
    continue
  }

  const code = byName.get(norm(name))
  if (code) map[id] = code
  else unmatched.push(`${id} — ${name}`)
}

const out = `// AUTO-GENERATED by scripts/generate-country-map.mjs — do not edit by hand.
//
// ISO 3166-1 numeric (as used by the world topology) to alpha-2 (as used everywhere
// else in this codebase). Keyed by code rather than by country name, because names
// differ between sources -- the topology says "W. Sahara" where Intl says
// "Western Sahara".
//
// ${Object.keys(map).length} of ${geometries.length} topology geometries mapped.

export const NUMERIC_TO_ALPHA2: Record<string, string> = ${JSON.stringify(map, null, 2)}

/** Alpha-2 to numeric, for looking up a geometry from a country code. */
export const ALPHA2_TO_NUMERIC: Record<string, string> = Object.fromEntries(
  Object.entries(NUMERIC_TO_ALPHA2).map(([numeric, alpha2]) => [alpha2, numeric]),
)
`

fs.writeFileSync(path.join(ROOT, "lib/geo/topology-map.ts"), out, "utf-8")

console.log(`Mapped ${Object.keys(map).length} of ${geometries.length} geometries.`)
if (unmatched.length) {
  console.log(`\nUnmatched (${unmatched.length}) — these will not be colourable:`)
  unmatched.forEach((u) => console.log("  " + u))
} else {
  console.log("Every geometry matched.")
}
